"""Read atlas alpha and author landmarks; source PNGs are never modified."""
from pathlib import Path
import json
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
GUIDES = json.loads((ROOT/"source_art/campaign/sofia_v4_guides/poses.json").read_text())
KEYS = ["hip","shoulder","neck","head","right_knee","right_ankle","right_tip","left_knee","left_ankle","left_tip"]

def annotate(clip, name, scale):
    image = Image.open(ROOT/"resources/campaign"/name)
    guide = GUIDES[clip]
    cols,rows = guide["columns"],guide["rows"]
    width,height = image.size
    cw,ch = width/cols,height/rows
    frames = []
    for i,frame in enumerate(guide["frames"]):
        cell = (int(i%cols*cw),int(i//cols*ch),int((i%cols+1)*cw),int((i//cols+1)*ch))
        alpha = image.getchannel("A").crop(cell)
        bounds = alpha.point(lambda a:255 if a>128 else 0).getbbox()
        box = [cell[0]+max(0,bounds[0]-2),cell[1]+max(0,bounds[1]-2),min(cell[2]-cell[0],bounds[2]+2)-max(0,bounds[0]-2),min(cell[3]-cell[1],bounds[3]+2)-max(0,bounds[1]-2)]
        points = {k:list(frame["points"][k]) for k in KEYS}
        if clip == "walk":
            points["hip"][1] += 7
            points["shoulder"][1] += 5
        elif clip == "run":
            for key in points: points[key][0] += 10
            points["hip"][1] -= 3
            points["shoulder"][1] += 6
        else:
            # Source crouch illustrations have their own torso construction.
            ox,oy = i%cols*cw,i//cols*ch
            points["hip"] = [ox+185,oy+198]
            points["shoulder"] = [ox+216,oy+122]
            points["neck"] = [ox+247,oy+94]
            points["head"] = [ox+280,oy+62]
        root = list(frame["root"])
        root[0] = points["hip"][0]
        if clip != "run": root[1] = cell[1]+bounds[3]-1
        frames.append({"box":box,"root":root,"scale":scale,"points":[points[k] for k in KEYS]})
    return {"size":[width,height],"keys":KEYS,"frames":frames}

def down():
    # Individually annotated regions: the generated rows are intentionally unequal
    # in height so crouching retains the same head/boot scale as standing.
    frames = []
    # Solid connected artwork bounds plus four pixels of padding. Two boots
    # cross nominal grid lines; rectangular grid cells would borrow their toes
    # into a neighbouring pose and cut the original heel at the same time.
    boxes = [[47,19,279,556],[390,26,348,549],[751,50,382,524],[1133,49,398,525],
             [12,612,347,376],[388,631,365,357],[774,632,380,357],[1157,644,375,344]]
    standing = [
        [[180,285],[151,148],[196,133],[230,91],[263,412],[282,535],[318,557],[108,415],[76,535],[91,557]],
        [[180,287],[153,156],[199,143],[234,103],[271,416],[298,535],[337,557],[101,417],[56,535],[77,557]],
        [[180,294],[151,166],[200,157],[237,124],[280,420],[315,536],[359,557],[91,420],[35,536],[58,557]],
        [[180,297],[151,174],[204,165],[239,135],[285,421],[326,537],[370,557],[84,421],[23,537],[45,557]]]
    crouching = [
        [[169,841],[172,717],[213,690],[264,681],[277,808],[294,945],[334,975],[160,950],[60,934],[40,963]],
        [[169,842],[173,728],[216,702],[267,698],[280,817],[298,946],[338,975],[158,956],[59,938],[40,965]],
        [[170,847],[171,737],[216,711],[268,711],[285,825],[304,947],[344,976],[155,960],[58,940],[40,967]],
        [[169,849],[171,743],[219,720],[272,724],[289,834],[310,948],[351,976],[149,960],[56,940],[39,967]]]
    for row,entries in enumerate([standing,crouching]):
        for col,points in enumerate(entries):
            oy = 0 # Crouch coordinates are already absolute on the whole canvas.
            ox = col*384
            actual = [[p[0]+ox,p[1]+oy] for p in points]
            frames.append({"box":boxes[row*4+col],"root":[ox+180,565 if row==0 else 982],"scale":.118,"points":actual})
    return {"size":[1536,1024],"keys":KEYS,"frames":frames}

if __name__ == "__main__":
    clips = {"walk":annotate("walk","sofia_walk_v4.png",.28),"run":annotate("run","sofia_run_v4.png",.28),"crouch_walk":annotate("crouch","sofia_crouch_walk_v4.png",.15),"down":down()}
    (ROOT/"source_art/campaign/sofia_v4_landmarks.json").write_text(json.dumps(clips,indent=2),encoding="utf-8")
    (ROOT/"resources/campaign/sofia_v4_landmarks.gd").write_text("extends RefCounted\n# Artwork-space annotations, generated by tools/annotate_sofia_cycles.py.\nconst CLIPS = "+json.dumps(clips,separators=(",",":"))+"\n",encoding="utf-8")
    print("Authored landmarks for",sum(len(c["frames"]) for c in clips.values()),"painted cels")
