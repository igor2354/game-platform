"""Compile only approved V4 geometry coordinates into an exportable Godot constant."""
from pathlib import Path
import hashlib
import json
from media_paths import media_path

def main():
    source=media_path('docs/locations/mvp_village/Кандидаты/forest_blueprint_v4_2026-10-25/forest_v4_plan.json')
    data=json.loads(source.read_text(encoding='utf-8'))
    assert data['version']==4 and data['length_m']==484 and len(data['jumps'])==19
    keep=['id','title','start_m','end_m','length_m','ground','ledges','route','branches','jumps']
    plan=dict(source_version=4,source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
              units_per_meter=data['reference']['units_per_meter'],length_m=data['length_m'],
              nodes=[{k:n[k] for k in keep} for n in data['nodes']],
              fatal_chasm=data['fatal_chasm'],relief_mix=data['relief_mix'])
    output=Path(__file__).resolve().parents[1]/'scripts/campaign/forest_prologue_v2_data.gd'
    output.write_text('extends RefCounted\n## V4 geometry approved for separate dry prologue on 2026-10-25. Generated by tools/prepare_forest_prologue_v2.py.\nconst PLAN = '+json.dumps(plan,ensure_ascii=False,separators=(',',':'))+'\n',encoding='utf-8')
    print(f'Compiled {len(plan["nodes"])} sections, 19 jumps, {plan["length_m"]} m; no media copied.')

if __name__=='__main__':main()
