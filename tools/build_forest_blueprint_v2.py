class Canvas:
    def __init__(self,w,h):
        self.w,self.h=w,h
        self.items=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">',
                    f'<rect width="{w}" height="{h}" fill="{BG}"/>',
                    '<g font-family="Segoe UI,Arial,sans-serif">']
        self.text_bounds=[]
    def raw(self,s): self.items.append(s)
    def poly(self,points,color=INK,width=2,fill='none',dash=None,close=False):
        tag='polygon' if close else 'polyline'
        self.raw(f'<{tag} points="'+ ' '.join(f'{x:.2f},{y:.2f}' for x,y in points)+f'" fill="{fill}" stroke="{color}" stroke-width="{width}" stroke-linejoin="round" stroke-linecap="round"'+(f' stroke-dasharray="{dash}"' if dash else '')+'/>')
    def rect(self,x,y,w,h,fill='none',stroke=INK,dash=None):
        self.raw(f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" fill="{fill}" stroke="{stroke}" stroke-width="1.8"'+(f' stroke-dasharray="{dash}"' if dash else '')+'/>')
    def circle(self,x,y,r,color=INK,fill='none'):
        self.raw(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{fill}" stroke="{color}" stroke-width="1.6"/>')
    def text(self,x,y,value,size=22,color=INK,bold=False,width=None):
        if size not in fonts: fonts[size]=ImageFont.truetype(FONT,size)
        f=fonts[size]; lines=[]
        for para in str(value).split('\n'):
            cur=''
            for word in para.split():
                trial=(cur+' '+word).strip()
                if width and cur and f.getlength(trial)>width: lines.append(cur);cur=word
                else: cur=trial
            lines.append(cur)
        lineheight=size*1.38
        for i,line in enumerate(lines):
            self.raw(f'<text x="{x}" y="{y+i*lineheight}" font-size="{size}" fill="{color}" font-weight="{600 if bold else 400}">{escape(line)}</text>')
            self.text_bounds.append((x,y+i*lineheight-size,float(f.getlength(line)),size*1.4))
        return y+len(lines)*lineheight
    def save(self,path):
        doc=''.join(self.items)+ '</g></svg>'
        ET.fromstring(doc)
        for x,y,w,h in self.text_bounds:
            assert x>=0 and y>=0 and x+w<self.w+4 and y+h<self.h+4,(path.name,x,y,w,h)
        path.write_text(doc,encoding='utf-8')

