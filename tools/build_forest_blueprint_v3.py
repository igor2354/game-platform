def matching(n,a,b):
    return next((j for j in n['jumps'] if tuple(j['a'])==tuple(a) and tuple(j['b'])==tuple(b)),None)

def route(c,n,path,p,color=MAIN):
    for a,b in zip(path,path[1:]):
        j=matching(n,a,b)
        if j:
            x,y=p(*a);xx,yy=p(*b);peak=min(y,yy)-1.1*abs(p(0,1)[1]-p(0,0)[1])
            c.raw(f'<path d="M {x} {y-4} Q {(x+xx)/2} {peak} {xx} {yy-4}" fill="none" stroke="{EVENT if j["fatal"] else JUMP}" stroke-width="3" stroke-dasharray="6 4"/>')
            c.text((x+xx)/2-10,peak-6,j['id'],13,EVENT if j['fatal'] else JUMP)
        else:c.poly([p(a[0],a[1]+.14),p(b[0],b[1]+.14)],color,3,dash='7 5' if color==ALT else None)

